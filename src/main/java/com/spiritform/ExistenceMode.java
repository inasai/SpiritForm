package com.spiritform;

/** Форма Існування: правила, за якими працює форма Привида (параметр конфігу existenceForm). */
public enum ExistenceMode {
    /** «Верхній світ»: усе працює як раніше. */
    OVERWORLD,
    /** «Незер»: Привидом стають лише через смерть, а повертає людську подобу вихід з одержимого моба. */
    NETHER,
    /** «Потойбіччя»: Привид отримує шкоду, а поза Потойбіччям форма триває лише хвилину. */
    BEYOND
}
